const bySlug = (slug: string): PortfolioItem => {
  const item = portfolio.find((p) => p.slug === slug);
  if (!item) throw new Error(`portfolio-index: suite "${slug}" is missing from portfolio-data.ts`);
  return item;
};
export const suites = SUITE_ORDER.map((slug) => ({ item: bySlug(slug), modules: MODULES[slug] }));
